export interface OnlineLesson {
  id: string;
  code: string;
  title: string;
}

export interface OnlineSection {
  id: string;
  title: string;
  lessons: OnlineLesson[];
}

export interface OnlineChapter {
  id: string;
  title: string;
  sections: OnlineSection[];
}

const L = (code: string, title: string): OnlineLesson => ({ id: code, code, title });

const S = (id: string, title: string, lessons: OnlineLesson[]): OnlineSection => ({
  id,
  title,
  lessons,
});

const C = (id: string, title: string, sections: OnlineSection[]): OnlineChapter => ({
  id,
  title,
  sections,
});

const flat = (id: string, lessons: OnlineLesson[]): OnlineSection => S(id, '', lessons);

