export const ALL_ONLINE_LESSONS: OnlineLesson[] = ONLINE_LESSON_CHAPTERS.flatMap((chapter) =>
  chapter.sections.flatMap((section) => section.lessons),
);

export function findOnlineLesson(id: string): OnlineLesson | undefined {
  return ALL_ONLINE_LESSONS.find((lesson) => lesson.id === id);
}

export function chapterIdForLesson(lessonId: string): string | undefined {
  for (const chapter of ONLINE_LESSON_CHAPTERS) {
    if (chapter.sections.some((section) => section.lessons.some((lesson) => lesson.id === lessonId))) {
      return chapter.id;
    }
  }
  return undefined;
}
