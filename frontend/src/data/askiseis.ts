export function askiseisForTheme(theme: AskisiThemeId): Askisi[] {
  return ASKISEIS.filter((a) => a.theme === theme);
}

export function pdfPathForAskisi(item: Askisi): string | null {
  if (!item.fileName) return null;
  return `${PDF_BASE_PATH}/${item.fileName}`;
}

function matchesSearch(item: Askisi, q: string): boolean {
  if (
    item.title.toLowerCase().includes(q) ||
    item.description?.toLowerCase().includes(q) ||
    item.publishedAt?.toLowerCase().includes(q)
  ) {
    return true;
  }
  const st = item.statement;
  if (!st) return false;
  if (st.intro.toLowerCase().includes(q)) return true;
  if (st.introClosing?.toLowerCase().includes(q)) return true;
  if (st.bullets?.some((b) => b.toLowerCase().includes(q))) return true;
  return st.tasks.some(
    (t) =>
      t.code.toLowerCase().includes(q) ||
      t.text.toLowerCase().includes(q) ||
      t.subItems?.some((s) => s.toLowerCase().includes(q))
  );
}

export function filterAskiseis(theme: AskisiThemeId, query: string): Askisi[] {
  const list = askiseisForTheme(theme);
  const q = query.trim().toLowerCase();
  if (!q) return list;
  return list.filter((item) => matchesSearch(item, q));
}
