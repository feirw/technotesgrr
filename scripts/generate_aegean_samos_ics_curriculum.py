def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def fmt_hours(lecture: float | None, lab: float | None) -> str | None:
    if lecture is None and lab is None:
        return None
    bits = []
    if lecture is not None:
        bits.append(f"lecture: {lecture}")
    if lab is not None:
        bits.append(f"lab: {lab}")
    return "{ " + ", ".join(bits) + " }"


def fmt_course(row: tuple) -> str:
    sem, code, ects, name, kind_key, lecture, lab = row
    kind = KIND_LABELS[kind_key]
    hours_obj = fmt_hours(lecture, lab)
    hours_part = f", hours: {hours_obj}" if hours_obj else ""
    return (
        f'      {{ code: "{esc(code)}", ects: {ects}, name: "{esc(name)}", '
        f'kind: "{esc(kind)}"{hours_part} }},'
    )


