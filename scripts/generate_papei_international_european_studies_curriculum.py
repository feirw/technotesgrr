def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main() -> None:
    by_sem: dict[int, list[tuple]] = {}
    for row in COURSES:
        by_sem.setdefault(row[0], []).append(row)

    lines = [
        "/** Πανεπιστήμιο Πειραιώς · Διεθνών και Ευρωπαϊκών Σπουδών */",
        "import type { SchoolCurriculum } from './schoolCurricula';",
        "",
        "export const PAPEI_INTERNATIONAL_EUROPEAN_STUDIES_CURRICULUM: SchoolCurriculum = {",
        '  title: "Διεθνών και Ευρωπαϊκών Σπουδών",',
        '  subtitle: "Πανεπιστήμιο Πειραιώς · Πειραιάς",',
        "  hoursNote:",
        '    "240 ECTS · 1ο–4ο: υποχρεωτικός κορμός · 5ο–7ο & 6ο–8ο: επιλογής '
        'από τον κατάλογο μαθημάτων · Πρακτική Άσκηση.",',
        "  semesters: [",
    ]

    for sem in sorted(by_sem):
        lines.append(f"    {{ semester: {sem}, courses: [")
        for _, code, ects, name, kind in by_sem[sem]:
            lines.append(
                f'      {{ code: "{esc(code)}", ects: {ects}, name: "{esc(name)}", '
                f'kind: "{esc(kind)}" }},'
            )
        lines.append("    ] },")

    lines.extend(["  ],", "};", ""])

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT} ({len(COURSES)} courses)")


if __name__ == "__main__":
    main()
