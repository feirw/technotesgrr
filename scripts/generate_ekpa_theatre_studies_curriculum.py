def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main() -> None:
    courses: list[tuple[int, str, int, str, str]] = [
        c(sem, code, name, Y) for sem, code, name in MANDATORY
    ]
    for code, name in ELECTIVES:
        courses.append(c(7, code, name, E))
    courses.append(c(8, "ΘΣ-ΠΑ01", "Πρακτική Άσκηση", PA, 6))
    courses.append(c(8, "ΘΣ-ΣΕ01", "Σεμινάριο", SM, 5))

    by_sem: dict[int, list[tuple]] = {}
    for row in courses:
        by_sem.setdefault(row[0], []).append(row)

    lines = [
        "/** ΕΚΠΑ · Θεατρικών Σπουδών (Αθήνα) */",
        "import type { SchoolCurriculum } from './schoolCurricula';",
        "",
        "export const EKPA_THEATRE_STUDIES_CURRICULUM: SchoolCurriculum = {",
        '  title: "Θεατρικών Σπουδών",',
        '  subtitle: "Εθνικό και Καποδιστριακό Πανεπιστήμιο Αθηνών · Αθήνα",',
        "  hoursNote:",
        (
            '    "240 ECTS · 8 εξάμηνα · υποχρεωτικά 1ο–8ο · επιλογής Γενικού '
            "Περιεχομένου (χειμερινό/εαρινό) · Πρακτική Άσκηση & Σεμινάριο. "
            'Κωδικοί ΘΣ-xxxx εκτιμώμενα · ECTS 5/μάθημα εκτός Πρακτικής.",'
        ),
        "  semesters: [",
    ]

    for sem in sorted(by_sem):
        lines.append(f"    {{ semester: {sem}, courses: [")
        for _s, code, ects, name, kind in by_sem[sem]:
            lines.append(
                f'      {{ code: "{esc(code)}", ects: {ects}, '
                f'name: "{esc(name)}", kind: "{esc(kind)}" }},'
            )
        lines.append("    ] },")

    lines.extend(["  ],", "};", ""])

    OUT.write_text("\n".join(lines), encoding="utf-8")
    total = sum(r[2] for r in courses)
    print(f"Wrote {OUT} ({len(courses)} courses, {total} ECTS catalog total)")


if __name__ == "__main__":
    main()
