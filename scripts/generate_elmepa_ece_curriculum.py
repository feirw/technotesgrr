def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def fmt_hours(theory: float, exercises: float, lab: float) -> str | None:
    if theory == 0 and exercises == 0 and lab == 0:
        return None
    bits = [f"lecture: {theory}"]
    if exercises:
        bits.append(f"tutorial: {exercises}")
    if lab:
        bits.append(f"lab: {lab}")
    return "{ " + ", ".join(bits) + " }"


def fmt_course(row: tuple) -> str:
    sem, code, ects, name, kind_key, theory, exercises, lab = row
    kind = KIND_LABELS[kind_key]
    hours_obj = fmt_hours(theory, exercises, lab)
    hours_part = f", hours: {hours_obj}" if hours_obj else ""
    return (
        f'      {{ code: "{esc(code)}", ects: {ects}, name: "{esc(name)}", '
        f'kind: "{esc(kind)}"{hours_part} }},'
    )


