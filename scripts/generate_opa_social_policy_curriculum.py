def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main() -> None:
    by_sem: dict[int, list[tuple]] = {}
    for row in COURSES:
        by_sem.setdefault(row[0], []).append(row)

    lines = [
        "/** Πάντειο · Κοινωνικής Πολιτικής (Αθήνα) */",
        "import type { SchoolCurriculum } from './schoolCurricula';",
        "",
        "export const OPA_SOCIAL_POLICY_CURRICULUM: SchoolCurriculum = {",
        '  title: "Κοινωνικής Πολιτικής",',
        '  subtitle: "Πάντειο Πανεπιστήμιο · Αθήνα",',
        "  hoursNote:",
        '    "240 ECTS · 8 εξάμηνα (ΕΣ1–ΕΣ4). Κωδικοί γραμματείας. '
        '7ο–8ο εξ.: σεμινάρια 12 ECTS · πτυχιακή εργασία 18 ECTS.",',
        "  semesters: [",
    ]

    for sem in sorted(by_sem):
        lines.append(f"    {{ semester: {sem}, courses: [")
        for _s, code, ects, name, kind in by_sem[sem]:
            lines.append(
                f'      {{ code: "{esc(code)}", ects: {ects}, name: "{esc(name)}", '
                f'kind: "{esc(kind)}" }},'
            )
        lines.append("    ] },")

    lines.extend(["  ],", "};", ""])

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT} ({len(COURSES)} courses)")


if __name__ == "__main__":
    main()
