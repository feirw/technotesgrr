def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def fmt(row: tuple) -> str:
    _sem, code, ects, name, kind, module, hours = row
    full_kind = f"{kind} · {module}"
    hours_part = ""
    if hours is not None:
        hours_part = f", hours: {{ lecture: {hours} }}"
    return (
        f'      {{ code: "{esc(code)}", ects: {ects}, name: "{esc(name)}", '
        f'kind: "{esc(full_kind)}"{hours_part} }},'
    )


