def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def fmt(code: str, name: str, kind: str) -> str:
    return (
        f'      {{ code: "{esc(code)}", ects: 6, name: "{esc(name)}", '
        f'kind: "{esc(kind)}" }},'
    )


def main() -> None:
    by_sem: dict[int, list[tuple]] = {}
    for sem, code, name, kind in COURSES:
        by_sem.setdefault(sem, []).append((code, name, kind))

