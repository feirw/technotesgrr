def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main() -> None:
    by_sem: dict[int, list[tuple[str, int, str, str]]] = {}
    for sem, code, ects, name, kind in COURSES:
        by_sem.setdefault(sem, []).append((code, ects, name, kind))

    lines = [
        "/** Πανεπιστήμιο Πατρών · Διοίκησης Τουρισμού */",
        "import type { SchoolCurriculum } from './schoolCurricula';",
        "",
        "export const UOP_PATRAS_TOURISM_MANAGEMENT_CURRICULUM: SchoolCurriculum = {",
        '  title: "Διοίκησης Τουρισμού",',
        '  subtitle: "Πανεπιστήμιο Πατρών · Πάτρα",',
        "  hoursNote:",
        '    "240 ECTS · 40 μαθήματα (35 υποχρεωτικά + 5 επιλογής). '
        '5ο–8ο εξ.: μαθήματα επιλογής · πτυχιακή · πρακτική.",',
        "  semesters: [",
    ]

    for sem in sorted(by_sem):
        lines.append(f"    {{ semester: {sem}, courses: [")
        for code, ects, name, kind in by_sem[sem]:
            lines.append(
                f'      {{ code: "{esc(code)}", ects: {ects}, name: "{esc(name)}", '
                f'kind: "{esc(kind)}" }},'
            )
        lines.append("    ] },")

    lines.extend(["  ],", "};", ""])

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT} ({len(COURSES)} courses)")


if __name__ == "__main__":
    main()
