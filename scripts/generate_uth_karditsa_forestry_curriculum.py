def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def fmt_hours(lec: int, tut: int, lab: int) -> str | None:
    if lec == tut == lab == 0:
        return None
    bits = [f"lecture: {lec}"]
    if tut:
        bits.append(f"tutorial: {tut}")
    if lab:
        bits.append(f"lab: {lab}")
    return "{ " + ", ".join(bits) + " }"


def main() -> None:
    by_sem: dict[int, list[tuple]] = {}
    for row in RAW:
        by_sem.setdefault(row[0], []).append(row)

    lines = [
        "/** Θεσσαλίας · Δασολογίας, Επιστημών Ξύλου & Σχεδιασμού (Καρδίτσα) */",
        "import type { SchoolCurriculum } from './schoolCurricula';",
        "",
        "export const UTH_KARDITSA_FORESTRY_CURRICULUM: SchoolCurriculum = {",
        '  title: "Δασολογίας, Επιστημών Ξύλου και Σχεδιασμού",',
        '  subtitle: "Πανεπιστήμιο Θεσσαλίας · Καρδίτσα",',
        "  hoursNote:",
        (
            '    "300 ECTS · 10 εξάμηνα · κοινός κορμός 1ο–6ο (ΚΜ). '
            "7ο–10ο: κατεύθυνση Διαχείρισης Περιβάλλοντος (ΔΠΥ/ΔΠΕ) ή "
            'Επιστημών Ξύλου (ΞΣΥ/ΞΣΕ). Ώρες/εβδ.: θεωρία · ασκήσεις · εργαστήριο.",'
        ),
        "  semesters: [",
    ]

    for sem in sorted(by_sem):
        lines.append(f"    {{ semester: {sem}, courses: [")
        for _s, code, ects, name, kind, lec, tut, lab in by_sem[sem]:
            hours = fmt_hours(lec, tut, lab)
            hours_part = f", hours: {hours}" if hours else ""
            lines.append(
                f'      {{ code: "{esc(code)}", ects: {ects}, '
                f'name: "{esc(name)}", kind: "{esc(kind)}"{hours_part} }},'
            )
        lines.append("    ] },")

    lines.extend(["  ],", "};", ""])

    OUT.write_text("\n".join(lines), encoding="utf-8")
    total = sum(r[2] for r in RAW)
    print(f"Wrote {OUT} ({len(RAW)} courses, {total} ECTS catalog total)")


