KIND_LABELS = {
    "YM": "Υποχρεωτικό (ΥΜ)",
    "PM": "Επιλογής",
}


def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def fmt_course(sem: int, code: str, ects: int, name: str, kind: str) -> str:
    return (
        f'      {{ code: "{esc(code)}", ects: {ects}, name: "{esc(name)}", '
        f'kind: "{esc(KIND_LABELS[kind])}" }},'
    )


def main() -> None:
    by_sem: dict[int, list[tuple]] = {}
    for row in COURSES:
        by_sem.setdefault(row[0], []).append(row)

    lines = [
        "/** AUTO-GENERATED — ΧΑΡΟΚΟΠΕΙΟ Πληροφορικής και Τηλεματικής πρόγραμμα σπουδών */",
        "import type { SchoolCurriculum } from './schoolCurricula';",
        "",
        "export const HAROKOPIO_INFORMATICS_CURRICULUM: SchoolCurriculum = {",
        '  title: "Πληροφορικής και Τηλεματικής",',
        '  subtitle: "ΧΑΡΟΚΟΠΕΙΟ · Αθήνα",',
        "  semesters: [",
    ]

    for sem in sorted(by_sem):
        lines.append(f"    {{ semester: {sem}, courses: [")
        for row in by_sem[sem]:
            lines.append(fmt_course(*row))
        lines.append("    ] },")

    lines.append("  ],")
    lines.append("};")
    lines.append("")

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT} ({len(COURSES)} courses)")


if __name__ == "__main__":
    main()
