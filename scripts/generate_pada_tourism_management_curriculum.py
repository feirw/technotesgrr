def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def fmt(row: tuple) -> str:
    _, code, ects, name, kind, hours = row
    hours_part = f", hours: {{ lecture: {hours} }}" if hours is not None else ""
    return (
        f'      {{ code: "{esc(code)}", ects: {ects}, name: "{esc(name)}", '
        f'kind: "{esc(kind)}"{hours_part} }},'
    )


def main() -> None:
    by_sem: dict[int, list[tuple]] = {}
    for row in COURSES:
        by_sem.setdefault(row[0], []).append(row)

    lines = [
        "/** ΠΑΔΑ · Διοίκησης Τουρισμού (Αιγάλεω) */",
        "import type { SchoolCurriculum } from './schoolCurricula';",
        "",
        "export const PADA_TOURISM_MANAGEMENT_CURRICULUM: SchoolCurriculum = {",
        '  title: "Διοίκησης Τουρισμού",',
        '  subtitle: "Πανεπιστήμιο Δυτικής Αττικής · Αιγάλεω",',
        "  hoursNote:",
        (
            '    "ΜΓΥ: μάθημα γενικού υποβάθρου · ΜΕΥ: μάθημα ειδικότητας υποχρεωτικό · '
            "ΜΕ: μάθημα ειδικότητας. 3ο–8ο εξ.: κατ' επιλογήν υποχρεωτικά ανά εξάμηνο. "
            '8ο εξ.: Η4 πρακτική άσκηση · Η5 πτυχιακή εργασία.",'
        ),
        "  semesters: [",
    ]

    for sem in sorted(by_sem):
        lines.append(f"    {{ semester: {sem}, courses: [")
        for row in by_sem[sem]:
            lines.append(fmt(row))
        lines.append("    ] },")

    lines.extend(["  ],", "};", ""])

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT} ({len(COURSES)} courses)")


if __name__ == "__main__":
    main()
