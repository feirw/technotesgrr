def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main() -> None:
    by_sem: dict[int, list[tuple[str, int, str, str]]] = {}

    for code, name in MANDATORY:
        by_sem.setdefault(1, []).append((code, 5, name, Y))

    for code, name in HISTORY_ME:
        by_sem.setdefault(2, []).append((code, 5, name, KI))

    for code, name in PHIL_ME:
        by_sem.setdefault(3, []).append((code, 5, name, KF))

    for i, (code, name) in enumerate(FREE):
        sem = 4 + (i // 12)
        by_sem.setdefault(sem, []).append((code, 5, name, E))

    lines = [
        "/** ΕΚΠΑ · Ιστορίας και Φιλοσοφίας της Επιστήμης (Αθήνα) */",
        "import type { SchoolCurriculum } from './schoolCurricula';",
        "",
        "export const EKPA_HISTORY_PHILOSOPHY_OF_SCIENCE_CURRICULUM: SchoolCurriculum = {",
        '  title: "Ιστορίας και Φιλοσοφίας της Επιστήμης",',
        '  subtitle: "Εθνικό και Καποδιστριακό Πανεπιστήμιο Αθηνών · Αθήνα",',
        "  hoursNote:",
        '    "240 ECTS · 8 εξάμηνα. 21 υποχρεωτικά · κατ\' επιλογήν υποχρεωτικά '
        "(προσανατολισμός Ιστορίας ή Φιλοσοφίας της Επιστήμης) · επιλογής. "
        'Ομαδοποίηση ανά κατηγορία (1ο=Υ · 2ο=ΥΕΙ · 3ο=ΥΕΦ · 4ο–7ο=Ε).",',
        "  semesters: [",
    ]

    for sem in sorted(by_sem):
        lines.append(f"    {{ semester: {sem}, courses: [")
        for code, ects, name, kind in by_sem[sem]:
            lines.append(
                f'      {{ code: "{esc(code)}", ects: {ects}, name: "{esc(name)}", '
                f'kind: "{esc(kind)}" }},'
            )
        lines.append("    ] },")

    lines.extend(["  ],", "};", ""])

    total = sum(len(v) for v in by_sem.values())
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT} ({total} courses)")


if __name__ == "__main__":
    main()
