def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main() -> None:
    by_sem: dict[int, list[tuple]] = {}
    for row in COURSES:
        by_sem.setdefault(row[0], []).append(row)

    lines = [
        "/** Πάντειο · Διεθνών και Ευρωπαϊκών Σπουδών (Αθήνα) */",
        "import type { SchoolCurriculum } from './schoolCurricula';",
        "",
        "export const PANTEION_INTERNATIONAL_EUROPEAN_STUDIES_CURRICULUM: SchoolCurriculum = {",
        '  title: "Διεθνών και Ευρωπαϊκών Σπουδών",',
        '  subtitle: "Πάντειο Πανεπιστήμιο Κοινωνικών & Πολιτικών Επιστημών · Αθήνα",',
        "  hoursNote:",
        (
            '    "240 ECTS · 8 εξάμηνα · 3ο–6ο: 2 επιλογής/εξάμηνο · 7ο–8ο: '
            "επιλογή θεματικού κύκλου (Πολιτική & Διακυβέρνηση ή Δίκαιο & "
            "Διακυβέρνηση) · 2 επιλογής/εξάμηνο · Πτυχιακή (= 2 μαθήματα). "
            'Κωδικοί ΔΕΣ-xxxx εκτιμώμενα · ECTS 5/μάθημα.",'
        ),
        "  semesters: [",
    ]

    for sem in sorted(by_sem):
        lines.append(f"    {{ semester: {sem}, courses: [")
        for _s, code, ects, name, kind in by_sem[sem]:
            lines.append(
                f'      {{ code: "{esc(code)}", ects: {ects}, '
                f'name: "{esc(name)}", kind: "{esc(kind)}" }},'
            )
        lines.append("    ] },")

    lines.extend(["  ],", "};", ""])

    OUT.write_text("\n".join(lines), encoding="utf-8")
    total = sum(r[2] for r in COURSES)
    print(f"Wrote {OUT} ({len(COURSES)} courses, {total} ECTS catalog total)")


