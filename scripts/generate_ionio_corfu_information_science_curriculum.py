def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main() -> None:
    by_sem: dict[int, list[tuple]] = {}
    for row in COURSES:
        by_sem.setdefault(row[0], []).append(row)

    lines = [
        "/** Ιόνιο · Επιστήμης της Πληροφορίας (Κέρκυρα) */",
        "import type { SchoolCurriculum } from './schoolCurricula';",
        "",
        "export const IONIO_CORFU_INFORMATION_SCIENCE_CURRICULUM: SchoolCurriculum = {",
        '  title: "Επιστήμης της Πληροφορίας",',
        '  subtitle: "Ιόνιο Πανεπιστήμιο · Κέρκυρα",',
        "  hoursNote:",
        (
            '    "240 ECTS · 8 εξάμηνα · υποχρεωτικά 1ο–4ο · κατ\' επιλογήν '
            "υποχρεωτικά 5ο–8ο · επιλογή ξένης γλώσσας (Αγγλικά/Γαλλικά/Ιταλικά). "
            'Κωδικοί ΕΠ-xxxx όπου λείπει επίσημος κωδικός.",'
        ),
        "  semesters: [",
    ]

    for sem in sorted(by_sem):
        lines.append(f"    {{ semester: {sem}, courses: [")
        for _s, code, ects, name, kind in by_sem[sem]:
            lines.append(
                f'      {{ code: "{esc(code)}", ects: {ects}, '
                f'name: "{esc(name)}", kind: "{esc(kind)}" }},'
            )
        lines.append("    ] },")

    lines.extend(["  ],", "};", ""])

    OUT.write_text("\n".join(lines), encoding="utf-8")
    total = sum(r[2] for r in COURSES)
    print(f"Wrote {OUT} ({len(COURSES)} courses, {total} ECTS catalog total)")


if __name__ == "__main__":
    main()
