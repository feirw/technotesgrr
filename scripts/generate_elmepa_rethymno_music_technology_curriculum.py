def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def fmt_hours(th: int | None, asks: int | None, lab: int | None) -> str:
    bits = []
    if th is not None:
        bits.append(f"lecture: {th}")
    if asks is not None:
        bits.append(f"tutorial: {asks}")
    if lab is not None:
        bits.append(f"lab: {lab}")
    if not bits:
        return ""
    return ", hours: { " + ", ".join(bits) + " }"


