def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def parse_hours(raw: str) -> str | None:
    if not raw:
        return None
    parts = raw.split("+")
    lecture = parts[0]
    lab = None
    for p in parts[1:]:
        if p.endswith("E"):
            lab = p[:-1]
        else:
            raise ValueError(f"Unknown hours segment: {p} in {raw}")
    bits = [f"lecture: {lecture}"]
    if lab:
        bits.append(f"lab: {lab}")
    return "{ " + ", ".join(bits) + " }"


def fmt_course(sem: int, code: str, ects: int, name: str, kind: str, hours: str) -> str:
    hours_obj = parse_hours(hours)
    hours_part = f", hours: {hours_obj}" if hours_obj else ""
    return (
        f'      {{ code: "{esc(code)}", ects: {ects}, name: "{esc(name)}", '
        f'kind: "{esc(KIND_LABELS[kind])}"{hours_part} }},'
    )


