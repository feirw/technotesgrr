def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def fmt(code: str, ects: int, name: str, kind: str) -> str:
    return (
        f'      {{ code: "{esc(code)}", ects: {ects}, name: "{esc(name)}", '
        f'kind: "{esc(kind)}" }},'
    )


def main() -> None:
    by_sem: dict[int, list[tuple]] = {}
    for row in COURSES:
        by_sem.setdefault(row[0], []).append(row)

    for code, name, ects in WINTER_ELECTIVES:
        by_sem.setdefault(5, []).append((5, code, ects, name, WIN))
        by_sem.setdefault(7, []).append((7, code, ects, name, WIN))

