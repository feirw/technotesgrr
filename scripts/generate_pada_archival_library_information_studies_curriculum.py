def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def fmt(row: tuple) -> str:
    sem, code, ects, name, kind, lec, lab = row
    hours_part = ""
    if lec is not None or lab is not None:
        lec_val = lec if lec is not None else 0
        if lab:
            hours_part = f", hours: {{ lecture: {lec_val}, lab: {lab} }}"
        elif lec_val:
            hours_part = f", hours: {{ lecture: {lec_val} }}"
    return (
        f'      {{ code: "{esc(code)}", ects: {ects}, name: "{esc(name)}", '
        f'kind: "{esc(kind)}"{hours_part} }},'
    )


