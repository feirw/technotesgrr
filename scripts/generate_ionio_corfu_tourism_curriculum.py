def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main() -> None:
    by_sem: dict[int, list[tuple]] = {}
    for row in COURSES:
        by_sem.setdefault(row[0], []).append(row)

    lines = [
        "/** Ιόνιο Πανεπιστήμιο · Τουρισμού (Κέρκυρα) */",
        "import type { SchoolCurriculum } from './schoolCurricula';",
        "",
        "export const IONIO_CORFU_TOURISM_CURRICULUM: SchoolCurriculum = {",
        '  title: "Τουρισμού",',
        '  subtitle: "Ιόνιο Πανεπιστήμιο · Κέρκυρα",',
        "  hoursNote:",
        (
            '    "240 ECTS · 8 εξάμηνα · 30 ECTS/εξάμηνο. '
            "1ο εξ.: 1 από 3 · 2ο εξ.: 2 από 3 · 3ο εξ.: 1 από 3 · "
            "4ο εξ.: 2 από 4 · 5ο εξ.: 3 από 5 · 6ο εξ.: 3 από 6 · "
            "7ο εξ.: 4 από 6 · 8ο εξ.: 6 από 9. "
            '6ο εξ.: πρακτική άσκηση 10 ECTS · 7ο εξ.: πτυχιακή 10 ECTS.",'
        ),
        "  semesters: [",
    ]

    for sem in sorted(by_sem):
        lines.append(f"    {{ semester: {sem}, courses: [")
        for _s, code, ects, name, kind in by_sem[sem]:
            lines.append(
                f'      {{ code: "{esc(code)}", ects: {ects}, name: "{esc(name)}", '
                f'kind: "{esc(kind)}" }},'
            )
        lines.append("    ] },")

    lines.extend(["  ],", "};", ""])

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT} ({len(COURSES)} courses)")


