CODE_IN_NAME = re.compile(r"\(([A-ZΑ-Ωa-zΑ-ω0-9./\s–-]+)\)\s*$")


def code_from(name: str, fallback: str) -> str:
    m = CODE_IN_NAME.search(name.strip())
    if m:
        raw = m.group(1).strip()
        if raw.startswith("ΣΓΠ"):
            return "ΣΓΠ-I" if "Ι " in raw or raw.endswith("Ι") else "ΣΓΠ-II"
        return raw.replace(" ", "")
    return fallback


