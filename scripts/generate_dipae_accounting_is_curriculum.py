def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def fmt_course(sem: int, code: str, ects: int, name: str, kind: str) -> str:
    return (
        f'      {{ code: "{esc(code)}", ects: {ects}, name: "{esc(name)}", '
        f'kind: "{esc(kind)}" }},'
    )


def main() -> None:
    by_sem: dict[int, list[tuple]] = {}
    for row in COURSES:
        by_sem.setdefault(row[0], []).append(row)

    lines = [
        "/** ΔΙΠΑΕ · Λογιστικής & Πληροφοριακών Συστημάτων (Θεσσαλονίκη) */",
        "import type { SchoolCurriculum } from './schoolCurricula';",
        "",
        "export const DIPAE_ACCOUNTING_IS_CURRICULUM: SchoolCurriculum = {",
        '  title: "Λογιστικής & Πληροφοριακών Συστημάτων",',
        '  subtitle: "Διεθνές Πανεπιστήμιο της Ελλάδος · Θεσσαλονίκη",',
        "  semesters: [",
    ]

    for sem in sorted(by_sem):
        lines.append(f"    {{ semester: {sem}, courses: [")
        for row in by_sem[sem]:
            lines.append(fmt_course(*row))
        lines.append("    ] },")

    lines.append("  ],")
    lines.append("};")
    lines.append("")

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT} ({len(COURSES)} courses)")


