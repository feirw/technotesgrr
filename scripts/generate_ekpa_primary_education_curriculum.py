SEASON_KIND = {"W": EW, "E": ES, "WE": EWES, "NX": NX}
SEASON_SEM = {"W": 7, "E": 8, "WE": 7, "NX": 7}


def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main() -> None:
    all_courses = list(COURSES)
    for code, name, season in FREE:
        all_courses.append((SEASON_SEM[season], code, 5, name, SEASON_KIND[season]))

    by_sem: dict[int, list[tuple]] = {}
    for row in all_courses:
        by_sem.setdefault(row[0], []).append(row)

    lines = [
        "/** ΕΚΠΑ · Παιδαγωγικό Δημοτικής Εκπαίδευσης (Αθήνα) */",
        "import type { SchoolCurriculum } from './schoolCurricula';",
        "",
        "export const EKPA_PRIMARY_EDUCATION_CURRICULUM: SchoolCurriculum = {",
        '  title: "Παιδαγωγικό Δημοτικής Εκπαίδευσης",',
        '  subtitle: "Εθνικό και Καποδιστριακό Πανεπιστήμιο Αθηνών · Αθήνα",',
        "  hoursNote:",
        '    "240 ECTS · 8 εξάμηνα. Κατ\' επιλογήν υποχρεωτικά: 2 (Αγωγής) + 2 '
        "(Ειδ. παιδαγωγικής) + 1 (Ανθρωπιστικών) + 1 (Μαθηματικών) + 1 "
        "(Φυσικών επιστημών). Ελεύθερης επιλογής από κατάλογο 7ο–8ο εξ. "
        'Β026: μόνο εισαχθέντες έως 2024-25 · Β034: υποχρεωτικό από 2025-26.",',
        "  semesters: [",
    ]

    for sem in sorted(by_sem):
        lines.append(f"    {{ semester: {sem}, courses: [")
        for _s, code, ects, name, kind in by_sem[sem]:
            lines.append(
                f'      {{ code: "{esc(code)}", ects: {ects}, name: "{esc(name)}", '
                f'kind: "{esc(kind)}" }},'
            )
        lines.append("    ] },")

    lines.extend(["  ],", "};", ""])

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT} ({len(all_courses)} courses)")


if __name__ == "__main__":
    main()
