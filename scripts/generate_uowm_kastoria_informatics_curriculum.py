KIND_LABELS = {
    "Y": "Υποχρεωτικό",
    "ELEP": "Ελεύθερης επιλογής",
    "PA": "Πρακτική Άσκηση",
    "PT": "Πτυχιακή Εργασία",
}


def kind_label(kind_key: str) -> str:
    if kind_key.startswith("EY:"):
        area = kind_key[3:]
        return f"Επιλογής ({area})"
    return KIND_LABELS[kind_key]


def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def fmt_course(row: tuple) -> str:
    sem, code, ects, name, kind_key, hours = row
    kind = kind_label(kind_key)
    hours_part = f", hours: {{ lecture: {hours} }}" if hours is not None else ""
    return (
        f'      {{ code: "{esc(code)}", ects: {ects}, name: "{esc(name)}", '
        f'kind: "{esc(kind)}"{hours_part} }},'
    )


def main() -> None:
    by_sem: dict[int, list[tuple]] = {}
    for row in COURSES:
        by_sem.setdefault(row[0], []).append(row)

    lines = [
        "/** AUTO-GENERATED — Πανεπιστήμιο Δυτικής Μακεδονίας, Πληροφορικής (Καστοριά) */",
        "import type { SchoolCurriculum } from './schoolCurricula';",
        "",
        "export const UOWM_KASTORIA_INFORMATICS_CURRICULUM: SchoolCurriculum = {",
        '  title: "Πληροφορικής",',
        '  subtitle: "Πανεπιστήμιο Δυτικής Μακεδονίας · Καστοριά",',
        '  hoursNote: "Ώρες/εβδομάδα. Επιστ. περιοχές: NET, SW, ACM, DCDM, HW. '
        'Ε\\\'–ΣΤ\\\': 3Υ+3ΕΥ ή 2ΕΥ+ΕΛΕΠ · ΣΤ\\\'–Ζ\\\'–Η\\\' ανάλογα. '
        'Πρακτική Άσκηση (6 ECTS) διαθέσιμη Ε\\\'–Η\\\' εξ. Πρόγραμμα 2023-2024.",',
        "  semesters: [",
    ]

    for sem in sorted(by_sem):
        lines.append(f"    {{ semester: {sem}, courses: [")
        for row in by_sem[sem]:
            lines.append(fmt_course(row))
        lines.append("    ] },")

    lines.append("  ],")
    lines.append("};")
    lines.append("")

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT} ({len(COURSES)} courses)")


if __name__ == "__main__":
    main()
