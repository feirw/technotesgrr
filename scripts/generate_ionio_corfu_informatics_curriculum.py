def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def fmt_hours(lecture: float | None, tutorial: float | None, lab: float | None) -> str | None:
    if lecture is None and tutorial is None and lab is None:
        return None
    bits = []
    if lecture is not None:
        bits.append(f"lecture: {lecture}")
    if tutorial is not None:
        bits.append(f"tutorial: {tutorial}")
    if lab is not None:
        bits.append(f"lab: {lab}")
    return "{ " + ", ".join(bits) + " }"


def fmt_course(row: tuple) -> str:
    sem, code, ects, name, kind_key, lecture, tutorial, lab = row
    kind = KIND_LABELS[kind_key]
    hours_obj = fmt_hours(lecture, tutorial, lab)
    hours_part = f", hours: {hours_obj}" if hours_obj else ""
    return (
        f'      {{ code: "{esc(code)}", ects: {ects}, name: "{esc(name)}", '
        f'kind: "{esc(kind)}"{hours_part} }},'
    )


def main() -> None:
    by_sem: dict[int, list[tuple]] = {}
    for row in COURSES:
        by_sem.setdefault(row[0], []).append(row)

    lines = [
        "/** AUTO-GENERATED — Ιόνιο Πανεπιστήμιο, Πληροφορικής (Κέρκυρα) */",
        "import type { SchoolCurriculum } from './schoolCurricula';",
        "",
        "export const IONIO_CORFU_INFORMATICS_CURRICULUM: SchoolCurriculum = {",
        '  title: "Πληροφορικής",',
        '  subtitle: "Ιόνιο Πανεπιστήμιο · Κέρκυρα",',
        '  hoursNote: "Θ = θεωρία, Φ = φροντιστήριο, Ε = εργαστήριο. '
        'Εξειδικεύσεις: ΒΥΝ, ΚΔΕ, ΨΜΑΔ · Εργαλειοθήκες ΤΒ1–ΤΒ5. '
        'MIN = υποχρεωτικό ελάχιστο εξειδίκευσης.",',
        "  semesters: [",
    ]

    for sem in sorted(by_sem):
        lines.append(f"    {{ semester: {sem}, courses: [")
        for row in by_sem[sem]:
            lines.append(fmt_course(row))
        lines.append("    ] },")

    lines.append("  ],")
    lines.append("};")
    lines.append("")

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT} ({len(COURSES)} courses)")


