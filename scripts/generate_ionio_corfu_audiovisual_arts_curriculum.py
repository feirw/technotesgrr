def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main() -> None:
    by_sem: dict[int, list[tuple]] = {}
    for row in COURSES:
        by_sem.setdefault(row[0], []).append(row)

    hours_note = (
        "300 ECTS · 10 εξάμηνα · 30 ECTS/εξάμηνο. "
        "Υ=υποχρεωτικό · Ε=επιλογής (από εκτεταμένο κατάλογο). "
        "Κάθε εξάμηνο (Γ΄–Θ΄) προσφέρεται και FRE: Ελεύθερη Επιλογή Μαθήματος "
        "(από το Τμήμα ή άλλο Τμήμα) — δεν περιλαμβάνεται εδώ. "
        "PRO750 Ατομική Εργασία 12 ECTS · PRO851 Πρακτική Άσκηση 6 ECTS · "
        "PRO050 Πτυχιακή Εργασία 30 ECTS (Ι΄ εξάμηνο)."
    )

    lines = [
        "/** Ιόνιο Πανεπιστήμιο · Τεχνών Ήχου και Εικόνας (Κέρκυρα) */",
        "import type { SchoolCurriculum } from './schoolCurricula';",
        "",
        "export const IONIO_CORFU_AUDIOVISUAL_ARTS_CURRICULUM: SchoolCurriculum = {",
        '  title: "Τεχνών Ήχου και Εικόνας",',
        '  subtitle: "Ιόνιο Πανεπιστήμιο · Κέρκυρα",',
        "  hoursNote:",
        f'    "{esc(hours_note)}",',
        "  semesters: [",
    ]

    for sem in sorted(by_sem):
        lines.append(f"    {{ semester: {sem}, courses: [")
        for _s, code, ects, name, kind in by_sem[sem]:
            lines.append(
                f'      {{ code: "{esc(code)}", ects: {ects}, '
                f'name: "{esc(name)}", kind: "{esc(kind)}" }},'
            )
        lines.append("    ] },")

    lines.extend(["  ],", "};", ""])

    OUT.write_text("\n".join(lines), encoding="utf-8")
    total = sum(r[2] for r in COURSES)
    print(f"Wrote {OUT} ({len(COURSES)} courses, {total} ECTS listed)")


if __name__ == "__main__":
    main()
