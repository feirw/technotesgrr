def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def parse_hours(raw: str) -> str | None:
    if not raw:
        return None
    parts = raw.split("+")
    lecture = parts[0]
    tutorial = None
    lab = None
    for p in parts[1:]:
        if p.endswith("F"):
            tutorial = p[:-1]
        elif p.endswith("E"):
            lab = p[:-1]
        else:
            raise ValueError(f"Unknown hours segment: {p} in {raw}")
    bits = [f"lecture: {lecture}"]
    if tutorial:
        bits.append(f"tutorial: {tutorial}")
    if lab:
        bits.append(f"lab: {lab}")
    return "{ " + ", ".join(bits) + " }"


def fmt_course(sem: int, code: str, ects: int, name: str, kind: str, hours: str) -> str:
    hours_obj = parse_hours(hours)
    hours_part = f", hours: {hours_obj}" if hours_obj else ""
    return (
        f'      {{ code: "{esc(code)}", ects: {ects}, name: "{esc(name)}", '
        f'kind: "{esc(KIND_LABELS[kind])}"{hours_part} }},'
    )


def main() -> None:
    by_sem: dict[int, list[tuple]] = {}
    for row in COURSES:
        by_sem.setdefault(row[0], []).append(row)

    lines = [
        "/** AUTO-GENERATED — ΔΙΠΑΕ Μηχανικών Πληροφορικής & Ηλεκτρονικών Συστημάτων */",
        "import type { SchoolCurriculum } from './schoolCurricula';",
        "",
        "export const DIPAE_CPE_CURRICULUM: SchoolCurriculum = {",
        '  title: "Μηχανικών Πληροφορικής & Ηλεκτρονικών Συστημάτων",',
        '  subtitle: "ΔΙΠΑΕ · Θεσσαλονίκη",',
        '  hoursNote: "Εβδομαδιαίες ώρες: Θ = θεωρία, Ε = εργαστήριο. '
        'ΥΠ = υποχρεωτικό, ΥΠ-ΕΠ = υποχρεωτικό-επιλογής, ΕΠ = επιλογής. '
        'Ομάδες: ΗΛΕΣ, ΠΔΤΝ, ΚΟΙΝ.",',
        "  semesters: [",
    ]

    for sem in sorted(by_sem):
        lines.append(f"    {{ semester: {sem}, courses: [")
        for row in by_sem[sem]:
            lines.append(fmt_course(*row))
        lines.append("    ] },")

    lines.append("  ],")
    lines.append("};")
    lines.append("")

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT} ({len(COURSES)} courses)")


