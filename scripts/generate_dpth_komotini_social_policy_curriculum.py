def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main() -> None:
    by_sem: dict[int, list[tuple[str, int, str, str]]] = {}

    for sem, code, name in MANDATORY:
        by_sem.setdefault(sem, []).append((code, 6, name, Y))

    for code, name, kind, sems in ELECTIVES:
        for sem in sems:
            by_sem.setdefault(sem, []).append((code, 6, name, kind))

    lines = [
        "/** ΔΠΘ · Κοινωνικής Πολιτικής (Κομοτηνή) */",
        "import type { SchoolCurriculum } from './schoolCurricula';",
        "",
        "export const DPTH_KOMOTINI_SOCIAL_POLICY_CURRICULUM: SchoolCurriculum = {",
        '  title: "Κοινωνικής Πολιτικής",',
        '  subtitle: "Δημοκρίτειο Πανεπιστήμιο Θράκης · Κομοτηνή",',
        "  hoursNote:",
        '    "240 ECTS · 8 εξάμηνα · 6 ECTS/μάθημα. Επιλογές Α (χειμ. 1ο+3ο) · Β (εαρινό 2ο+4ο) · '
        "Γ (χειμ. 5ο+7ο) · Δ (εαρινό 6ο+8ο). "
        '1ο: 4Υ+1Ε · 2ο: 4Υ+1Ε · 3ο–4ο: 3Υ+2Ε · 5ο–6ο: 2Υ+3Ε · 7ο–8ο: 1Υ+4Ε.",',
        "  semesters: [",
    ]

    for sem in sorted(by_sem):
        lines.append(f"    {{ semester: {sem}, courses: [")
        for code, ects, name, kind in by_sem[sem]:
            lines.append(
                f'      {{ code: "{esc(code)}", ects: {ects}, name: "{esc(name)}", '
                f'kind: "{esc(kind)}" }},'
            )
        lines.append("    ] },")

    lines.extend(["  ],", "};", ""])

    total = sum(len(v) for v in by_sem.values())
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT} ({total} course entries)")


if __name__ == "__main__":
    main()
