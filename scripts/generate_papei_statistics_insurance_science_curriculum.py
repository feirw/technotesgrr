def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main() -> None:
    by_sem: dict[int, list[tuple[str, int, str, str]]] = {}
    sem_counters: dict[int, int] = {}

    for sem, name, kind in RAW:
        sem_counters[sem] = sem_counters.get(sem, 0) + 1
        code = f"SSA-{sem:02d}-{sem_counters[sem]:02d}"
