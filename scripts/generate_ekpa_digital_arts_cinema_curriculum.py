def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main() -> None:
    by_sem: dict[int, list[tuple]] = {}
    for row in COURSES:
        by_sem.setdefault(row[0], []).append(row)

    hours_note = (
        "240 ECTS · 8 εξάμηνα · 28 υποχρεωτικά × 5 ECTS + πτυχιακή 20 ECTS. "
        "Εισαγωγή 2025-26: 14 μαθήματα επιλογής × 5 ECTS + πρακτική 10 ECTS (προαιρετική). "
        "46508 Ακαδημαϊκή Έρευνα: προαπαιτούμενο πτυχιακής. "
        "Μέγιστο 12 μαθήματα/εξάμηνο (προτεινόμενο 6). "
        "Πηγή: Πρόγραμμα Διδασκαλίας 2024-25 / ΠΠΣ 2025-26."
    )

    lines = [
        "/** ΕΚΠΑ · Ψηφιακών Τεχνών και Κινηματογράφου (Ψαχνά Ευβοίας) */",
        "import type { SchoolCurriculum } from './schoolCurricula';",
        "",
        "export const EKPA_DIGITAL_ARTS_CINEMA_CURRICULUM: SchoolCurriculum = {",
        '  title: "Ψηφιακών Τεχνών και Κινηματογράφου",',
        '  subtitle: "ΕΚΠΑ · Ψαχνά Ευβοίας",',
        "  hoursNote:",
        f'    "{esc(hours_note)}",',
        "  semesters: [",
    ]

    for sem in sorted(by_sem):
        lines.append(f"    {{ semester: {sem}, courses: [")
        for _s, code, ects, name, kind in by_sem[sem]:
            lines.append(
                f'      {{ code: "{esc(code)}", ects: {ects}, '
                f'name: "{esc(name)}", kind: "{esc(kind)}" }},'
            )
        lines.append("    ] },")

    lines.extend(["  ],", "};", ""])

    OUT.write_text("\n".join(lines), encoding="utf-8")
    total = sum(r[2] for r in COURSES)
    print(f"Wrote {OUT} ({len(COURSES)} courses, {total} ECTS listed)")


