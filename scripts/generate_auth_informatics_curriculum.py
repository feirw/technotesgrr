def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def fmt_ects(value: float | int) -> str:
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    return str(value)


def fmt_course(sem: int, code: str, ects: float, name: str, kind: str) -> str:
    return (
        f'      {{ code: "{esc(code)}", ects: {fmt_ects(ects)}, name: "{esc(name)}", '
        f'kind: "{esc(KIND_LABELS[kind])}" }},'
    )


def main() -> None:
    by_sem: dict[int, list[tuple]] = {}
    for row in COURSES:
        by_sem.setdefault(row[0], []).append(row)

    lines = [
        "/** AUTO-GENERATED — ΑΠΘ Πληροφορικής πλήρες πρόγραμμα σπουδών (90 μαθήματα) */",
        "import type { SchoolCurriculum } from './schoolCurricula';",
        "",
        "export const AUTH_INFORMATICS_CURRICULUM: SchoolCurriculum = {",
        '  title: "Πληροφορικής",',
        '  subtitle: "ΑΠΘ · Θεσσαλονίκη",',
        "  semesters: [",
    ]

    for sem in sorted(by_sem):
        lines.append(f"    {{ semester: {sem}, courses: [")
        for row in by_sem[sem]:
            lines.append(fmt_course(*row))
        lines.append("    ] },")

    lines.append("  ],")
    lines.append("};")
    lines.append("")

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT} ({len(COURSES)} courses)")


if __name__ == "__main__":
    main()
