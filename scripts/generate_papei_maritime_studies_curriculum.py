def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def fmt(row: tuple) -> str:
    _, code, ects, name, kind, lecture = row
    return (
        f'      {{ code: "{esc(code)}", ects: {ects}, name: "{esc(name)}", '
        f'kind: "{esc(kind)}", hours: {{ lecture: {lecture} }} }},'
    )


