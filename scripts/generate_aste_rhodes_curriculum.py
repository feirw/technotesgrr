def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def fmt(row: tuple) -> str:
    _sem, code, ects, name, kind, lecture, lab = row
    if lecture is not None:
        if lab is not None:
            hours_part = f", hours: {{ lecture: {lecture}, lab: {lab} }}"
        else:
            hours_part = f", hours: {{ lecture: {lecture} }}"
    else:
        hours_part = ""
    return (
        f'      {{ code: "{esc(code)}", ects: {ects}, name: "{esc(name)}", '
        f'kind: "{esc(kind)}"{hours_part} }},'
    )


def main() -> None:
    by_sem: dict[int, list[tuple]] = {}
    for row in COURSES:
        by_sem.setdefault(row[0], []).append(row)

    lines = [
        "/** ΑΣΤΕ · Αστε Ρόδου (ΑΣΤΕΡ) */",
        "import type { SchoolCurriculum } from './schoolCurricula';",
        "",
        "export const ASTE_RHODES_CURRICULUM: SchoolCurriculum = {",
        '  title: "Διοίκηση Τουριστικών και Ξενοδοχειακών Επιχειρήσεων",',
        '  subtitle: "Ανώτατη Σχολή Τουριστικής Εκπαίδευσης · Ρόδος",',
        "  hoursNote:",
        '    "180 ECTS · 6 εξάμηνα · 30 ECTS/εξάμηνο. '
        "5ο & 6ο εξ.: επιλογή μίας εξειδίκευσης (Βιώσιμη Ανάπτυξη · "
        "Πολυτελής Φιλοξενία · Τεχνολογία και Καινοτομία). "
        'Θ=θεωρία, Ε=εργαστήριο.",',
        "  semesters: [",
    ]

    for sem in sorted(by_sem):
        lines.append(f"    {{ semester: {sem}, courses: [")
        for row in by_sem[sem]:
            lines.append(fmt(row))
        lines.append("    ] },")

    lines.extend(["  ],", "};", ""])

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT} ({len(COURSES)} courses)")


if __name__ == "__main__":
    main()
