def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def fmt_course(row: tuple) -> str:
    _sem, code, ects, name, kind, *rest = row
    hours = rest[0] if rest else None
    hours_part = ""
    if hours is not None:
        hours_part = f", hours: {{ lecture: {hours} }}"
    return (
        f'      {{ code: "{esc(code)}", ects: {ects}, name: "{esc(name)}", '
        f'kind: "{esc(kind)}"{hours_part} }},'
    )


