def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def fmt_ects(val: float) -> str:
    if val == int(val):
        return str(int(val))
    return str(val)


def fmt_hours(lec: int, tut: int, lab: int) -> str | None:
    if lec == tut == lab == 0:
        return None
    bits = [f"lecture: {lec}"]
    if tut:
        bits.append(f"tutorial: {tut}")
    if lab:
        bits.append(f"lab: {lab}")
    return "{ " + ", ".join(bits) + " }"


def main() -> None:
    by_sem: dict[int, list[tuple]] = {}
    for row in RAW:
        by_sem.setdefault(row[0], []).append(row)

    lines = [
        "/** Αιγαίου · Γεωγραφίας (Μυτιλήνη) */",
        "import type { SchoolCurriculum } from './schoolCurricula';",
        "",
        "export const AEGEAN_MYTILENE_GEOGRAPHY_CURRICULUM: SchoolCurriculum = {",
        '  title: "Γεωγραφίας",',
        '  subtitle: "Πανεπιστήμιο Αιγαίου · Μυτιλήνη",',
        "  hoursNote:",
        (
            '    "240 ECTS · 8 εξάμηνα · 1ο–4ο: υποχρεωτικά · 5ο–7ο: ΚΕΥ κατευθύνσεις '
            "(Φυσική Γεωγραφία · Ανθρωπογεωγραφία · Ανάπτυξη & Σχεδιασμός · "
            'Γεωπληροφορική) + επιλογής · πτυχιακή 10 ECTS. '
            'Ώρες/εβδ.: παραδόσεις (Θ) · φροντιστήριο (Φ) · εργαστήριο (Ε).",'
        ),
        "  semesters: [",
    ]

    for sem in sorted(by_sem):
        lines.append(f"    {{ semester: {sem}, courses: [")
        for _s, code, ects, name, kind, lec, tut, lab in by_sem[sem]:
            hours = fmt_hours(lec, tut, lab)
            hours_part = f", hours: {hours}" if hours else ""
            lines.append(
                f'      {{ code: "{esc(code)}", ects: {fmt_ects(ects)}, '
                f'name: "{esc(name)}", kind: "{esc(kind)}"{hours_part} }},'
            )
        lines.append("    ] },")

    lines.extend(["  ],", "};", ""])

    OUT.write_text("\n".join(lines), encoding="utf-8")
    total = sum(r[2] for r in RAW)
    print(f"Wrote {OUT} ({len(RAW)} courses, {total} ECTS catalog total)")


if __name__ == "__main__":
    main()
