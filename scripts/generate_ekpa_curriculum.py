def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def fmt_slots(slots: dict) -> str:
    if not slots:
        return ""
    parts = [f'{k}: "{v}"' for k, v in sorted(slots.items())]
    return ", slots: { " + ", ".join(parts) + " }"


def fmt_course(code, ects, name, kind, slots) -> str:
    return (
        f'      {{ code: "{esc(code)}", ects: {ects}, name: "{esc(name)}", '
        f'kind: "{esc(kind)}"{fmt_slots(slots)} }},'
    )


