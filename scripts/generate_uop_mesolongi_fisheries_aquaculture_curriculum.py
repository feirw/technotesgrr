def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def fmt_hours(lec: int, tut: int, lab: int) -> str | None:
    if lec == tut == lab == 0:
        return None
    bits = [f"lecture: {lec}"]
    if tut:
        bits.append(f"tutorial: {tut}")
    if lab:
        bits.append(f"lab: {lab}")
    return "{ " + ", ".join(bits) + " }"


def main() -> None:
    by_sem: dict[int, list[tuple]] = {}
    for row in RAW:
        by_sem.setdefault(row[0], []).append(row)

    lines = [
        "/** Πάτρας · Αλιείας & Υδατοκαλλιεργειών (Μεσολόγγι) */",
        "import type { SchoolCurriculum } from './schoolCurricula';",
        "",
        "export const UOP_MESOLONGI_FISHERIES_AQUACULTURE_CURRICULUM: SchoolCurriculum = {",
        '  title: "Αλιείας & Υδατοκαλλιεργειών",',
        '  subtitle: "Πανεπιστήμιο Πατρών · Μεσολόγγι",',
        "  hoursNote:",
        (
            '    "300 ECTS · 10 εξάμηνα · 1ο–8ο: υποχρεωτικά (8ο: +1 επιλογής 5 ECTS). '
            "9ο–10ο: διπλωματική (30 ECTS) + επιλογές 3/5 ECTS. "
            'Ώρες/εβδ.: παραδόσεις (ΩΠ) · φροντιστήρια (ΩΦ) · εργαστήρια (ΩΕ).",'
        ),
        "  semesters: [",
    ]

    for sem in sorted(by_sem):
        lines.append(f"    {{ semester: {sem}, courses: [")
        for _s, code, ects, name, kind, lec, tut, lab in by_sem[sem]:
            hours = fmt_hours(lec, tut, lab)
            hours_part = f", hours: {hours}" if hours else ""
            lines.append(
                f'      {{ code: "{esc(code)}", ects: {ects}, '
                f'name: "{esc(name)}", kind: "{esc(kind)}"{hours_part} }},'
            )
        lines.append("    ] },")

    lines.extend(["  ],", "};", ""])

    OUT.write_text("\n".join(lines), encoding="utf-8")
    total = sum(r[2] for r in RAW)
    print(f"Wrote {OUT} ({len(RAW)} courses, {total} ECTS catalog total)")


if __name__ == "__main__":
    main()
