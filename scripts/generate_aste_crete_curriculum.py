def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def fmt(row: tuple) -> str:
    _sem, code, ects, name, kind, lecture, lab = row
    if lecture is not None:
        if lab is not None:
            hours_part = f", hours: {{ lecture: {lecture}, lab: {lab} }}"
        else:
            hours_part = f", hours: {{ lecture: {lecture} }}"
    else:
        hours_part = ""
    return (
        f'      {{ code: "{esc(code)}", ects: {ects}, name: "{esc(name)}", '
        f'kind: "{esc(kind)}"{hours_part} }},'
    )


